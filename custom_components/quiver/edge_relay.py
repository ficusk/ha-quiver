"""Resource-bounded host for Quiver's pure outbound JavaScript relay.

The quiver sends one self-contained program during the WebSocket handshake.
It receives and returns JSON text only.  No Python callable is exposed to the
JavaScript context, so the program cannot reach Home Assistant, the filesystem,
or the network.
"""

from __future__ import annotations

from collections.abc import Callable
from concurrent.futures import ThreadPoolExecutor
import json
from threading import Lock
from typing import Any

import quickjs

_MEMORY_LIMIT = 16 * 1024 * 1024
_STACK_LIMIT = 512 * 1024
_TIME_LIMIT_SECONDS = 0.02


class EdgeRelayError(RuntimeError):
    """The negotiated edge relay could not load or process a frame."""


class EdgeRelay:
    """Run one negotiated pure-JavaScript relay in an isolated context."""

    def __init__(self, source: str) -> None:
        if not source.strip():
            raise EdgeRelayError("relay source is empty")

        source_json = json.dumps(source)
        program = f"""
"use strict";
const __quiverRelay = (0, eval)({source_json});
if (
  !__quiverRelay ||
  typeof __quiverRelay !== "object" ||
  typeof __quiverRelay.onMessage !== "function"
) {{
  throw new TypeError("edge relay must provide onMessage(frame, state)");
}}
let __quiverRelayState = JSON.parse(
  JSON.stringify(__quiverRelay.initialState ?? {{}}),
);

function __quiverProcess(frame) {{
  const step = __quiverRelay.onMessage(frame, __quiverRelayState);
  if (step === undefined || step === null) return "[]";
  if (typeof step !== "object") {{
    throw new TypeError("edge relay step must be an object or undefined");
  }}
  if (Object.prototype.hasOwnProperty.call(step, "state")) {{
    __quiverRelayState = step.state;
  }}
  const outgoing =
    step.send === undefined
      ? []
      : Array.isArray(step.send)
        ? step.send
        : [step.send];
  if (!outgoing.every((candidate) => typeof candidate === "string")) {{
    throw new TypeError("edge relay send values must be JSON text frames");
  }}
  return JSON.stringify(outgoing);
}}

// The source has loaded. Remove dynamic-code entrypoints before frames arrive.
globalThis.eval = undefined;
globalThis.Function = undefined;
"""

        self._lifecycle_lock = Lock()
        self._executor: ThreadPoolExecutor | None = ThreadPoolExecutor(
            max_workers=1,
            thread_name_prefix="quiver-edge-relay",
        )
        self._runner: Callable[[str], Any] | None = None
        try:
            self._runner = self._executor.submit(
                self._compile_runner, program
            ).result()
        except Exception as err:  # noqa: BLE001 - translated at the boundary
            self._executor.shutdown(wait=True, cancel_futures=True)
            self._executor = None
            raise EdgeRelayError(f"could not load relay: {err}") from err

    @staticmethod
    def _compile_runner(program: str) -> Callable[[str], Any]:
        """Create and use the QuickJS context on one dedicated worker."""

        context = quickjs.Context()
        context.set_memory_limit(_MEMORY_LIMIT)
        context.set_max_stack_size(_STACK_LIMIT)
        context.set_time_limit(_TIME_LIMIT_SECONDS)
        context.eval(program)
        process = context.get("__quiverProcess")

        # The closure retains the context. Calls and final release both run on
        # the same worker because QuickJS contexts cannot move across threads.
        def run(frame: str) -> Any:
            return process(frame)

        return run

    def close(self) -> None:
        """Release the QuickJS context on its owning worker."""

        with self._lifecycle_lock:
            executor = self._executor
            if executor is None:
                return
            self._executor = None
            release = executor.submit(self._release_runner)
        release.result()
        executor.shutdown(wait=True, cancel_futures=True)

    def _release_runner(self) -> None:
        self._runner = None

    def process(self, frame: dict[str, Any]) -> list[dict[str, Any]]:
        """Return the JSON frames admitted or generated by the relay."""

        encoded = json.dumps(frame, default=str, separators=(",", ":"))
        try:
            with self._lifecycle_lock:
                executor = self._executor
                runner = self._runner
                if executor is None or runner is None:
                    raise EdgeRelayError("relay is closed")
                result = executor.submit(runner, encoded)
            raw = result.result()
            outgoing = json.loads(raw)
        except EdgeRelayError:
            raise
        except Exception as err:  # noqa: BLE001 - translated at the boundary
            raise EdgeRelayError(f"relay execution failed: {err}") from err

        if not isinstance(outgoing, list):
            raise EdgeRelayError("relay returned a non-list frame result")
        frames: list[dict[str, Any]] = []
        for candidate in outgoing:
            if not isinstance(candidate, str):
                raise EdgeRelayError("relay returned a non-text frame")
            try:
                frame_value = json.loads(candidate)
            except json.JSONDecodeError as err:
                raise EdgeRelayError("relay returned invalid JSON text") from err
            if not isinstance(frame_value, dict):
                raise EdgeRelayError("relay returned a non-object JSON frame")
            frames.append(frame_value)
        return frames
